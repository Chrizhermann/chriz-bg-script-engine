"""Build bgse/lua/M_BGSE.lua, the runtime the component installs (EEex autoloads M_*.lua)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'bgse/lua/M_BGSE.lua'
RECORDER_TARGET = ROOT / 'bgse/lua/M_BGSERC.lua'
MODULES = ('kernel.manifest', 'kernel.trace', 'kernel.hook', 'kernel.rng', 'combat-intent.spells',
           'combat-intent.targeting', 'combat-intent.ids', 'combat-intent.harm', 'combat-intent.mind', 'combat-intent.threat', 'combat-intent.openers',
           'combat-intent.weapons', 'combat-intent.arsenal', 'combat-intent.backstab', 'combat-intent.touch', 'combat-intent.defence', 'combat-intent.care', 'combat-intent.summons', 'combat-intent.orders', 'combat-intent.encounters', 'combat-intent.removal', 'combat-intent.zones', 'combat-intent.choice', 'combat-intent.director', 'combat-intent.doors', 'combat-intent.search', 'combat-intent.stealth', 'combat-intent.prep', 'combat-intent.talk','adapters.eeex.resources', 'adapters.eeex.sense', 'adapters.eeex.creature',
           'adapters.eeex.director', 'adapters.eeex.doors', 'adapters.eeex.search', 'adapters.eeex.stealth', 'adapters.eeex.choice', 'adapters.eeex.lower', 'adapters.eeex.hook', 'adapters.eeex.runtime')
VERSION = '0.1.0-dev'

# The playtest recorder intentionally has a separate M_ autoload file.  It must remain usable
# when component 0 (and therefore the combat engine bundle) is not installed.
RECORDER_MODULES = ('adapters.eeex.recorder',)


def build() -> str:
    return bundle(MODULES, 'adapters.eeex.runtime', 'M_BGSE')


def bundle(modules: tuple[str, ...], entry: str, label: str) -> str:
    lines = ['-- Chriz BG Script Engine runtime. Generated by tools/build_runtime.py from the authored',
             '-- modules in this repository; edit those, then rebuild.',
             '-- Builds on Sword Coast Stratagems (DavidW) and Spell Revisions (Demivrgvs, Gibberlings Three).',
             'local factories,loaded={},{}',
             'local function require(name)',
             '  if loaded[name] then return loaded[name] end',
             "  local value=assert(factories[name],'unbundled module')(require)",
             '  loaded[name]=value;return value', 'end']
    for name in modules:
        source = (ROOT / (name.replace('.', '/') + '.lua')).read_text(encoding='utf-8')
        lines.extend((f'factories[{json.dumps(name)}]=function(require)', source.rstrip('\n'), 'end'))
    if entry == 'adapters.eeex.runtime':
        lines += ["local ok,err=pcall(require('adapters.eeex.runtime').install,_G,{version=" + json.dumps(VERSION) + '})',
                  "if not ok then print('[BGSE] runtime not installed: '..tostring(err)) end"]
    else:
        lines += ["local ok,err=pcall(require(" + json.dumps(entry) + ').install,_G)',
                  "if not ok then print('[" + label + "] not installed: '..tostring(err)) end"]
    return '\n'.join(lines) + '\n'


def build_recorder() -> str:
    return bundle(RECORDER_MODULES, 'adapters.eeex.recorder', 'BGSE recorder')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed file is stale')
    args = parser.parse_args()
    text = build()
    recorder = build_recorder()
    if args.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.is_file() else None
        recorder_current = RECORDER_TARGET.read_text(encoding='utf-8') if RECORDER_TARGET.is_file() else None
        if current != text or recorder_current != recorder:
            stale = TARGET if current != text else RECORDER_TARGET
            raise SystemExit(f'{stale} is stale; run tools/build_runtime.py')
        raise SystemExit(0)
    TARGET.write_text(text, encoding='utf-8', newline='\n')
    RECORDER_TARGET.write_text(recorder, encoding='utf-8', newline='\n')
    print(f'Built {TARGET.relative_to(ROOT)} from {len(MODULES)} engine modules and '
          f'{len(RECORDER_MODULES)} recorder module')


if __name__ == '__main__':
    main()
